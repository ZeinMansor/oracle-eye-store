create table sales.customers (
    customer_id  number generated by default as identity minvalue 1 maxvalue 9999999999999999999999999999 increment by 1 cache 20 noorder
    nocycle nokeep noscale not null enable,
    name         varchar2(100 byte) not null enable,
    country_code varchar2(2 byte) not null enable,
    credit_limit number(12, 2) default 0 not null enable,
    created_at   date default sysdate not null enable,
    notes        varchar2(400 byte)
);

alter table sales.customers
    add constraint customers_pk primary key ( customer_id )
        using index enable;
